    /// <summary>The grouping's key counts whole cells of height either way, so 511 above a 256 room is one step and 512 two.</summary>
    [Theory]
    [InlineData(512f, 512f, 0)]
    [InlineData(767f, 512f, 0)]
    [InlineData(768f, 512f, 1)]
    [InlineData(256f, 768f, 2)]
    [InlineData(1024f, 512f, 2)]
    public void TheHeightKeyCountsWholeCells(float height, float first, int steps) =>
        Assert.Equal(steps, LevelGenerator.HeightSteps(height, first, Cell));

    /// <summary>
    /// The walls left once large rooms stand must still join every occupied
    /// cell: a tall room without a socket towards the rest walls it off, and
    /// the same room with one does not.
    /// </summary>
    [Fact]
    public void LargeRoomsMustLeaveTheCellsJoined()
    {
        // Three cells in a row, the middle large; masks by candidate: 0 has
        // east and west sockets, 1 only east.
        bool[] occupied = [true, true, true];
        int[] maskOf = [1 | 2, 1];
        Assert.True(LevelGenerator.Joined(occupied, [-1, 0, -1], maskOf, 1, 3));
        Assert.False(LevelGenerator.Joined(occupied, [-1, 1, -1], maskOf, 1, 3));
        Assert.True(LevelGenerator.Joined(occupied, [-1, -1, -1], maskOf, 1, 3));
        Assert.True(LevelGenerator.Joined([false, false], [-1, -1], maskOf, 1, 2));
    }

    /// <summary>The large rooms of a level, grouped by shared walls, each group in cell order.</summary>
    private static List<List<(int X, int Y)>> Groups(LevelGrid level, Dictionary<string, RoomDefinition> byName)
    {
        bool Large(int x, int y) =>
            x >= 0 && y >= 0 && x < level.Columns && y < level.Rows && level[x, y] is { } cell && LevelGenerator.IsLarge(byName[cell.Room]);

        HashSet<(int, int)> seen = [];
        List<List<(int X, int Y)>> groups = [];
        for (int y = 0; y < level.Rows; y++)
        {
            for (int x = 0; x < level.Columns; x++)
            {
                if (!Large(x, y) || !seen.Add((x, y)))
                {
                    continue;
                }

                List<(int X, int Y)> group = [(x, y)];
                for (int i = 0; i < group.Count; i++)
                {
                    foreach ((int dx, int dy) in new[] { (1, 0), (-1, 0), (0, 1), (0, -1) })
                    {
                        (int nx, int ny) = (group[i].X + dx, group[i].Y + dy);
                        if (Large(nx, ny) && seen.Add((nx, ny)))
                        {
                            group.Add((nx, ny));
                        }
                    }
                }

                groups.Add(group);
            }
        }

        return groups;
    }

    /// <summary>The world walls a placed room has sockets on, as (dx, dy) steps.</summary>
    private static HashSet<(int, int)> Sockets(LevelGrid level, Dictionary<string, RoomDefinition> byName, int x, int y)
    {
        LevelCell cell = level[x, y]!;
        RoomTransform transform = new(new RoomPlacement(cell.Room, 0, 0, cell.Rotation), 1f);
        HashSet<(int, int)> steps = [];
        foreach (RoomSocket socket in byName[cell.Room].Sockets)
        {
            (int axis, int sign) = transform.WorldNormal(socket.Facing);
            steps.Add(axis == 0 ? (sign, 0) : (0, sign));
        }

        return steps;
    }

    /// <summary>A group's rooms reach one another through their own joints alone.</summary>
    private static void AssertJoinedInside(LevelGrid level, Dictionary<string, RoomDefinition> byName, List<(int X, int Y)> group)
    {
        HashSet<(int, int)> members = [.. group];
        HashSet<(int, int)> reached = [group[0]];
        Queue<(int X, int Y)> queue = new([group[0]]);
        while (queue.Count > 0)
        {
            (int x, int y) = queue.Dequeue();
            foreach ((int dx, int dy) in Sockets(level, byName, x, y))
            {
                (int nx, int ny) = (x + dx, y + dy);
                if (members.Contains((nx, ny)) && Sockets(level, byName, nx, ny).Contains((-dx, -dy)) && reached.Add((nx, ny)))
                {
                    queue.Enqueue((nx, ny));
                }
            }
        }

        Assert.Equal(members.Count, reached.Count);
    }

    /// <summary>Every wall shared by two rooms has a socket on both sides or on neither.</summary>
    private static void AssertLinesUp(LevelGrid level, Dictionary<string, RoomDefinition> byName)
    {
        foreach ((int x, int y, _) in level.Placed)
        {
            HashSet<(int, int)> here = Sockets(level, byName, x, y);
            foreach ((int dx, int dy) in new[] { (1, 0), (0, 1) })
            {
                (int nx, int ny) = (x + dx, y + dy);
                if (nx < level.Columns && ny < level.Rows && level[nx, ny] is not null)
                {
                    Assert.Equal(here.Contains((dx, dy)), Sockets(level, byName, nx, ny).Contains((-dx, -dy)));
                }
            }
        }
    }
